def get_catalog_products(category: str = "") -> List[ProductItem]:
    if not category:
        return list(CATALOG_PRODUCTS)
    cat_lower = category.lower().strip()
    matches = [p for p in CATALOG_PRODUCTS if p.category.lower() == cat_lower]
    return matches if matches else list(CATALOG_PRODUCTS)
